#!/usr/bin/env python3
"""City Under Siege's page functions paired with each other map page's (docs/EXTRA_MAPS.md, Maps on other stages).

The extra maps' page features (the texts, the added weapons, the laser, the tests' forced bodies) were made on the
US n003a page's addresses. Every map page links the same code at other addresses: a function of the same shape
(mips2shape.py: the same code but for its relocated fields) in the same order is the same function. The pages'
tables (gen/g_<page>_table.cpp: each recompiled function's US address and its shape) are aligned page by page on
n003a's (difflib's matching blocks over the shapes), each pair with the function's length in n003a (to its next
function), and written as gen/g_page_map.cpp for the platform (ps2world.cpp P3, A3).

    python3 tools/page_map.py <gen dir> [--out FILE]

No byte of the game in the output: addresses only.
"""
import argparse
import difflib
import os
import re
import sys

PAGES = ['n001a', 'n002a', 'n011a', 'n012a', 'n013a', 'n021a', 'n022a', 'n024a', 'n031a', 'n032a', 'n033a']
BASE = 'n003a'


def table(gen, page):
    """[(address, shape)] of a page's recompiled functions, by address"""
    src = open(os.path.join(gen, 'g_%s_table.cpp' % page)).read()
    return sorted((int(a, 16), s) for a, s in re.findall(r'\{0x([0-9a-f]+), (S_[0-9a-f]+)\}', src))


def pairs(base, other):
    """[(n003a address, its length, the page's address)] of the functions in the same place of both sequences"""
    sm = difflib.SequenceMatcher(None, [s for _, s in base], [s for _, s in other], autojunk=False)
    out = []
    for i, j, n in sm.get_matching_blocks():
        for k in range(n):
            a = base[i + k][0]
            end = base[i + k + 1][0] if i + k + 1 < len(base) else a + 4
            out.append((a, end - a, other[j + k][0]))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('gen')
    ap.add_argument('--out')
    a = ap.parse_args()
    out = a.out or os.path.join(a.gen, 'g_page_map.cpp')
    base = table(a.gen, BASE)
    lines = ['// generated by tools/page_map.py, do not edit', '#include <cstdint>', 'namespace pagemap {',
             'struct Pair { uint32_t n3, len, page; };', 'struct Map { const char* page; const Pair* pairs; int count; };']
    maps = []
    for p in PAGES:
        if not os.path.exists(os.path.join(a.gen, 'g_%s_table.cpp' % p)):
            continue
        pr = pairs(base, table(a.gen, p))
        lines.append('static const Pair k_%s[] = {' % p)
        lines += ['  {%#x, %#x, %#x},' % x for x in pr]
        lines.append('};')
        maps.append((p, len(pr)))
        print('%s: %d of n003a\'s %d functions paired' % (p, len(pr), len(base)))
    lines.append('extern const Map kMaps[] = {%s};' % ', '.join('{"%s", k_%s, %d}' % (p, p, n) for p, n in maps))
    lines.append('extern const int kMapCount = %d;' % len(maps))
    lines.append('extern const uint32_t kN3Lo = %#x, kN3Hi = %#x;   // n003a\'s code' % (base[0][0], base[-1][0] + 4))
    lines.append('}  // namespace pagemap')
    open(out, 'w').write('\n'.join(lines) + '\n')
    print(out)
    return 0


if __name__ == '__main__':
    sys.exit(main())
