#!/usr/bin/env python3
"""The page signatures the native build recognizes a loaded page by, and the base images' hashes,
as a generated source (no bytes of the game in it: FNV-1a hashes only):

    python page_heads.py <images dir> <out.cpp> [page ...] [--version NAME <images dir> ...]

<images dir> holds mgs3_n_base.bin and <page>_<file>.bin (ps2_images.py): the US program's, and
with --version each other version's (docs/VERSIONS.md). With a page list, only those pages (the
ones recompiled): several r_ pages of the disc are the same bytes as r_sna01_n, and the first page
of a hash is the one the platform selects. The platform hashes the first 64 bytes at the version's
page address when the game's stage loader has put a page there, and the base image it inflates
from MGS3_N.ELF: its hash leaves out the word at +4 (the loader stub's checksum lands there),
and so do the hashes of its 4 KB blocks (a patched copy of a program is known by most of them).
"""
import glob, os, struct, sys


def fnv1a64(data):
    h = 0xcbf29ce484222325
    for b in data:
        h ^= b
        h = (h * 0x100000001b3) & 0xffffffffffffffff
    return h


def base_hash(base):
    return fnv1a64(base[:4] + b'\0\0\0\0' + base[8:])


BLOCK = 4096


def block_hashes(base):
    """the base image's 4 KB blocks (the word at +4 left out): a patched copy of a program is
    recognized by most of its blocks (disc.cpp MatchProgram)"""
    b = base[:4] + b'\0\0\0\0' + base[8:]
    return [fnv1a64(b[k:k + BLOCK]) for k in range(0, len(b), BLOCK)]


def pages(d, only):
    rows, load = [], None
    for path in sorted(glob.glob(os.path.join(d, '*_*.bin'))):
        name = os.path.basename(path)
        if name.startswith('mgs3_n_base'):
            continue
        page = name[:name.rfind('_')]
        if only and page not in only:
            continue
        head = open(path, 'rb').read(64)
        rows.append((page, fnv1a64(head)))
        if load is None:
            load = struct.unpack_from('<I', head, 0)[0]
    return rows, load


def main():
    args = sys.argv[1:]
    versions = []
    while '--version' in args:
        k = args.index('--version')
        versions.append((args[k + 1], args[k + 2]))
        del args[k:k + 3]
    if len(args) < 2:
        print(__doc__)
        return 2
    d, out, only = args[0], args[1], set(args[2:])
    base = open(os.path.join(d, 'mgs3_n_base.bin'), 'rb').read()
    rows, load = pages(d, only)
    allrows = [('US', p, h) for p, h in rows]
    bases = [('US', base_hash(base), len(base), load or 0x2DA680, block_hashes(base))]
    for name, vd in versions:
        vb = open(os.path.join(vd, 'mgs3_n_base.bin'), 'rb').read()
        vr, vl = pages(vd, only)
        allrows += [(name, p, h) for p, h in vr]
        bases.append((name, base_hash(vb), len(vb), vl or 0x2DA680, block_hashes(vb)))
    t = ['// Generated by tools/page_heads.py: each version\'s pages by the hash of their first 64 bytes, its base\n',
         '// image by the hash of its bytes (FNV-1a 64; the base\'s word at +4 left out), where its pages load\n',
         '#include <cstdint>\n\nnamespace ps2world {\n\n',
         'struct PageHead { const char* version; const char* page; uint64_t head; };\n',
         'struct VersionBase { const char* version; uint64_t hash; uint32_t size; uint32_t pageBase; const uint64_t* blocks; uint32_t blockCount; };\n',
         'extern const PageHead kPageHeads[];\nextern const int kPageHeadCount;\n',
         'extern const VersionBase kVersionBases[];\nextern const int kVersionBaseCount;\n',
         'extern const uint64_t kBaseImageHash;\nextern const uint32_t kBaseImageSize;\n\n',
         'const PageHead kPageHeads[] = {\n']
    t += [f'    {{"{v}", "{page}", 0x{h:016x}ull}},\n' for v, page, h in allrows]
    t += ['};\n', f'const int kPageHeadCount = {len(allrows)};\n']
    for v, h, n, pb, bl in bases:                      # each base image's 4 KB blocks
        t += [f'static const uint64_t kBlocks{v}[] = {{\n'] + [f'    0x{x:016x}ull,\n' for x in bl] + ['};\n']
    t += ['const VersionBase kVersionBases[] = {\n']
    t += [f'    {{"{v}", 0x{h:016x}ull, {n}, {pb:#x}, kBlocks{v}, {len(bl)}}},\n' for v, h, n, pb, bl in bases]
    # the US program's kernel stubs by their syscall number (the platform serves them at those
    # addresses; another version's stubs are served by their number)
    w = struct.unpack_from(f'<{len(base) // 4}I', base)
    stubs = {}
    for k in range(0, min(len(w), (0x201b00 - 0x100000) // 4) - 4):
        if (w[k] & 0xffff0000) != 0x24030000:
            continue
        for j in (1, 2):
            if w[k + j] == 0x0000000c and (w[k + j + 1] == 0x03e00008 or w[k + j + 2] == 0x03e00008):
                n = w[k] & 0xffff
                n = n - 0x10000 if n & 0x8000 else n
                stubs.setdefault(n, []).append(0x100000 + 4 * k)
                break
    t += ['};\n', f'const int kVersionBaseCount = {len(bases)};\n',
          'struct UsStub { int number; uint32_t addr; };\nextern const UsStub kUsStubs[];\nextern const int kUsStubCount;\n',
          'const UsStub kUsStubs[] = {\n'] + [f'    {{{n}, {a:#x}}},\n' for n, al in sorted(stubs.items()) for a in al] + ['};\n', f'const int kUsStubCount = {sum(len(al) for al in stubs.values())};\n',
          f'const uint64_t kBaseImageHash = 0x{fnv1a64(base):016x}ull;\n',
          f'const uint32_t kBaseImageSize = {len(base)};\n\n}}  // namespace ps2world\n']
    text = ''.join(t)
    if not (os.path.exists(out) and open(out).read() == text):      # unchanged: its object stays up to date
        open(out, 'w').write(text)
    print(f'{out}: {len(allrows)} pages of {len(bases)} version(s)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
