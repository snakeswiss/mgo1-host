#!/usr/bin/env python3
"""The source package: every source of the project, nothing of the game.

    python source_zip.py <out.zip>

Takes the project's own files (build_all.sh, the platform, the recompilers, the PC program, the
mod, the libraries it builds from source (third_party: Opus), the tools, the tests, the docs, the updater's server files, the dedicated host and MGO1 Host) and leaves out what a build makes or what comes from the
user's disc: the generated code (MGO1Loader/gen), objects, programs, the disc's files and the
code images, the launcher's pictures cut from Konami's Port Checker, logs, account files.
Refuses to write a package in which a file still looks generated from the game, or says it was made
from a leak.
"""
import os, re, sys, zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOP = ['build_all.sh', 'CHANGES.md', 'MGO1_PC_HANDOFF.md']
DIRS = ['MGO1Loader', 'recomp', 'native', 'mod', 'launcher', 'proxy', 'minhook', 'third_party', 'tools', 'tests', 'docs', 'port', 'server', 'host', 'hostpanel']
SKIP_DIRS = {'gen', 'obj', 'objO2', '__pycache__', 'build', 'out', 'deps', 'dist'}
SKIP_EXT = {'.o', '.obj', '.exe', '.dll', '.asi', '.bin', '.dat', '.elf', '.ipk', '.irx', '.img', '.iso',
            '.pcap', '.pcapng', '.local', '.log', '.tmp', '.zip', '.rc~'}
# made by the build (tools/launcher_art.py, native/build.sh)
SKIP_FILES = {'native/res/banner.png', 'native/res/mgo1.ico', 'native/res/savemgo_logo.png', 'native/res/build.rc',
              'hostpanel/res/savemgo.png'}
# binaries that are sources: the HD textures' upscaler (Real-ESRGAN's weights, BSD 3-Clause, tools/texture_model.py)
KEEP_FILES = {'native/hd/upscaler.bin'}
GENERATED = re.compile(rb'generated by (mips2cpp|recomp/vu2cpp|iop2cpp)', re.I)
# a file that says it was made from a leak: never in the package (docs/STAGE_DAT.md: our own notes); the
# pattern in two parts so that this file does not match it
LEAKED = re.compile(rb'from leak' + rb'ed [^\n]{0,60}sources', re.I)


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    out = os.path.abspath(sys.argv[1])
    files = [t for t in TOP if os.path.isfile(os.path.join(ROOT, t))]
    for d in DIRS:
        for base, dirs, names in os.walk(os.path.join(ROOT, d)):
            dirs[:] = sorted(x for x in dirs if x not in SKIP_DIRS)
            for n in sorted(names):
                rel = os.path.relpath(os.path.join(base, n), ROOT).replace(os.sep, '/')
                if rel not in KEEP_FILES and (os.path.splitext(n)[1].lower() in SKIP_EXT or rel in SKIP_FILES):
                    continue
                files.append(rel)
    bad = []
    for rel in files:
        data = open(os.path.join(ROOT, rel), 'rb').read()
        if GENERATED.search(data[:4096]):
            bad.append(rel)
        if LEAKED.search(data):
            sys.exit(f'{rel}: says it was made from a leak: not in the package')
    if bad:
        sys.exit('generated from the game, not a source: ' + ', '.join(bad))
    with zipfile.ZipFile(out, 'w', zipfile.ZIP_DEFLATED) as z:
        for rel in files:
            z.write(os.path.join(ROOT, rel), 'MGO1_PC_source/' + rel)
    print(f'{out}: {len(files)} files, {os.path.getsize(out)} bytes')
    return 0


if __name__ == '__main__':
    sys.exit(main())
