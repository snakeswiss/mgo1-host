#!/usr/bin/env python3
"""Writes the files built into MGO1 Host on Linux and macOS: a C++ file defining plat::Resource
(platform.h) with the same resources as Windows' app.rc (its RCDATA and ICON lines, the numbers of
resource.h): the fonts, the SaveMGO logo, app.ico. Or one picture of app.ico (its PNG entries) as a
PNG file, for the Linux desktop entry and the macOS icon.

    python3 res/embed.py <out.cpp>
    python3 res/embed.py --icon <size> <out.png>
"""
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def literal(data):
    """bytes as C string literal pieces (octal escapes, three digits each)."""
    out, line = [], []
    width = 0
    for b in data:
        if 32 <= b < 127 and b not in (34, 63, 92):        # not '"', '?', '\\'
            piece = chr(b)
        else:
            piece = "\\%03o" % b
        line.append(piece)
        width += len(piece)
        if width >= 120:
            out.append('"' + "".join(line) + '"')
            line, width = [], 0
    if line or not out:
        out.append('"' + "".join(line) + '"')
    return "\n    ".join(out)


def icon(size, out):
    d = open(os.path.join(HERE, "app.ico"), "rb").read()
    for i in range(struct.unpack("<H", d[4:6])[0]):
        w, h, _, _, _, _, n, off = struct.unpack("<BBBBHHII", d[6 + 16 * i:22 + 16 * i])
        if (w or 256) == size and (h or 256) == size and d[off:off + 8] == b"\x89PNG\r\n\x1a\n":
            open(out, "wb").write(d[off:off + n])
            return
    sys.exit("embed.py: no %d x %d PNG in app.ico" % (size, size))


def main():
    if len(sys.argv) == 4 and sys.argv[1] == "--icon":
        icon(int(sys.argv[2]), sys.argv[3])
        return
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    ids = {}
    for m in re.finditer(r"^#define\s+(\w+)\s+(\d+)", open(os.path.join(HERE, "resource.h"), encoding="utf-8").read(), re.M):
        ids[m.group(1)] = int(m.group(2))
    items = []
    for m in re.finditer(r'^(\w+)\s+(RCDATA|ICON)\s+"([^"]+)"', open(os.path.join(HERE, "app.rc"), encoding="utf-8").read(), re.M):
        name, path = m.group(1), os.path.normpath(os.path.join(HERE, m.group(3)))
        if name not in ids:
            sys.exit("embed.py: %s is not in resource.h" % name)
        items.append((name, ids[name], open(path, "rb").read()))
    if not items:
        sys.exit("embed.py: no resource in app.rc")
    out = ["// Generated by res/embed.py from res/app.rc: do not edit.",
           '#include "platform.h"',
           "#include <cstddef>",
           "",
           "namespace {"]
    for name, num, data in items:
        out.append("// %s (%d bytes)" % (name, len(data)))
        out.append("const char k%s[] =\n    %s;" % (name, literal(data)))
    out.append("struct Item { int id; const char* data; size_t size; };")
    out.append("const Item kItems[] = {")
    for name, num, data in items:
        out.append("    {%d, k%s, sizeof k%s - 1}," % (num, name, name))
    out.append("};")
    out.append("}  // namespace")
    out.append("")
    out.append("bool plat::Resource(int id, const void*& data, size_t& size) {")
    out.append("    for (const Item& i : kItems)")
    out.append("        if (i.id == id) { data = i.data; size = i.size; return true; }")
    out.append("    return false;")
    out.append("}")
    with open(sys.argv[1], "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("embed.py: %d resources, %d bytes -> %s" % (len(items), sum(len(d) for _, _, d in items), sys.argv[1]))


if __name__ == "__main__":
    main()
