#!/usr/bin/env python3
"""The IOP's sound modules, recompiled: Konami's sound library (sdlib.irx) and the network mode's
sound driver (sddrv_mn.irx) from MODNCD.IPK (the package the online game loads; MODULE.IPK's
sddrv_m.irx is the story mode's build, with another sound memory layout), loaded at fixed IOP
addresses (tools/irx.py) and turned into C++ in namespace iop (MGO1Loader/iop_rt.h: the IOP's own
memory, calls, kernel).

    python3 iop2cpp.py <dir with sdlib.irx and sddrv_mn.irx> <out prefix, e.g. MGO1Loader/gen/iop>
    (recomp/ipk_extract.py writes MODNCD.IPK's modules to a folder)

Writes <prefix>_decls.h, <prefix>_NN.cpp, <prefix>_table.cpp (functions by address, the modules'
entries, import stubs and export tables, and the FNV-1a hash of each loaded image, which the
runtime checks against the modules it loads from the user's disc).
"""
import os
import struct
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'tools'))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import irx          # noqa: E402
import mips2cpp     # noqa: E402

# where the runtime loads each module (MGO1Loader/iop.cpp kModules: the same bases)
MODULES = [('sdlib', 'sdlib.irx', 0x00100000), ('sddrv_mn', 'sddrv_mn.irx', 0x00110000)]


def jump_table_targets(words, base, lo, hi):
    """The case addresses of the switch statements' jump tables (lui at, hi; addu at, at, rX;
    lw rX, lo(at); jr rX, bounded by an sltiu before): code inside their function, not function
    starts (find_functions takes a table word landing after a `jr ra` for a function pointer)."""
    out = set()
    n = len(words)
    for i in range((lo - base) // 4, (hi - base) // 4):
        w = words[i]
        if (w >> 26) != 0 or (w & 63) != 0x08 or ((w >> 21) & 31) == 31:
            continue
        reg = (w >> 21) & 31
        table, count = None, None
        for k in range(i - 1, max(i - 10, 0), -1):
            x = words[k]
            if table is None and (x >> 26) == 0x23 and ((x >> 16) & 31) == reg:        # lw reg, lo(base)
                b, off = (x >> 21) & 31, x & 0xffff
                off = off - 0x10000 if off & 0x8000 else off
                for j in range(k - 1, max(k - 8, 0), -1):
                    y = words[j]
                    if (y >> 26) == 0x0f and ((y >> 16) & 31) == b:                   # lui base, hi
                        table = (((y & 0xffff) << 16) + off) & 0xffffffff
                        break
            if (x >> 26) == 0x0b:                                                     # sltiu: the case count
                count = x & 0xffff
                break
        if table is None or not (base <= table < base + 4 * n):
            continue
        for e in range(count if count else 256):
            t = words[(table - base) // 4 + e] if (table - base) // 4 + e < n else 0
            if not (lo <= t < hi and t % 4 == 0):
                break
            out.add(t)
    return out


def fnv(b):
    h = 0xcbf29ce484222325
    for x in b:
        h = ((h ^ x) * 0x100000001b3) & 0xffffffffffffffff
    return h


def main():
    src, out = sys.argv[1], sys.argv[2]
    mods = []
    fns = []
    for name, fname, base in MODULES:
        m = irx.load(os.path.join(src, fname), base)
        words = struct.unpack_from(f'<{len(m.image) // 4}I', m.image)
        stubs_at = min(a for a, _ in m.import_libs) if m.import_libs else m.text_end
        if getattr(m, 'export_table', None) is not None:          # the export table sits in .text too
            stubs_at = min(stubs_at, m.export_table)
        found = mips2cpp.find_functions(words, base, base, stubs_at)
        calls = {(w & 0x3ffffff) << 2 for w in words if (w >> 26) == 3}
        cases = jump_table_targets(words, base, base, stubs_at) - calls
        starts = sorted(({f.start for f in found} - cases) | {m.entry} |
                        {a for fl in m.exports.values() for a in fl if base <= a < stubs_at})
        for k, s in enumerate(starts):
            e = starts[k + 1] if k + 1 < len(starts) else stubs_at
            f = mips2cpp.Fn(s, e)
            f.words, f.base = words, base
            fns.append(f)
        mods.append((name, base, m))
        print(f'{name}: {len(starts)} functions, text {base:#x}-{stubs_at:#x}, image {len(m.image):#x}, hash {fnv(m.image):016x}, '
              f'{len(cases)} switch cases')
    mips2cpp.PREFIX = ''
    head = ['// generated by iop2cpp.py, do not edit', '#pragma once', '#include "iop_rt.h"', 'namespace iop {']
    head += [f'void F_{f.start:08x}(Ctx& c);' for f in fns]
    head.append('}  // namespace iop')
    open(out + '_decls.h', 'w').write('\n'.join(head) + '\n')
    files = 0
    for k in range(0, len(fns), 120):
        body = ['// generated by iop2cpp.py, do not edit', f'#include "{os.path.basename(out)}_decls.h"', 'namespace iop {']
        for f in fns[k:k + 120]:
            mips2cpp.emit_fn(body, f, f.words, f.base, None)
        body.append('}  // namespace iop')
        open(f'{out}_{files:02d}.cpp', 'w').write('\n'.join(body) + '\n')
        files += 1
    tab = ['// generated by iop2cpp.py, do not edit', f'#include "{os.path.basename(out)}_decls.h"', 'namespace iop {',
           'const FnEntry kFunctions[] = {']
    tab += [f'  {{{f.start:#x}, F_{f.start:08x}}},' for f in fns]
    tab += ['};', f'const int kFunctionCount = {len(fns)};', '']
    tab.append('// the modules as this build recompiled them: name, base, image size, entry, FNV-1a of the loaded image')
    tab.append('const ModuleInfo kModules[] = {')
    for name, base, m in mods:
        tab.append(f'  {{"{name}", {base:#x}, {len(m.image):#x}, {m.entry:#x}, {fnv(m.image):#018x}ull}},')
    tab += ['};', f'const int kModuleCount = {len(mods)};', '']
    tab.append('// import stubs: address, library, function index')
    tab.append('const ImportStub kImports[] = {')
    for name, base, m in mods:
        for a, (lib, n) in sorted(m.imports.items()):
            tab.append(f'  {{{a:#x}, "{lib}", {n}}},')
    tab += ['};', f'const int kImportCount = {sum(len(m.imports) for _, _, m in mods)};', '']
    tab.append('// export tables: library, function index, address')
    tab.append('const ExportEntry kExports[] = {')
    n = 0
    for name, base, m in mods:
        for lib, fl in m.exports.items():
            for i, a in enumerate(fl):
                tab.append(f'  {{"{lib}", {i}, {a:#x}}},')
                n += 1
    tab += ['};', f'const int kExportCount = {n};', '}  // namespace iop']
    open(out + '_table.cpp', 'w').write('\n'.join(tab) + '\n')
    print(f'{len(fns)} functions in {files} files + table')


if __name__ == '__main__':
    main()
